/**
 * Time zone IDs from Thales Sentinel EMS (customer / activation).
 * `value` is the IANA zone ID; `label` is the Thales "Location" column only
 * (GMT offset + description) so the dropdown stays readable and GMT-ordered.
 * @see https://docs.sentinel.thalesgroup.com/softwareandservices/ems/EMSdocs/WSG/Content/TimeZone.htm
 */
export type StandardTimezoneOption = { readonly value: string; readonly label: string };

/**
 * Thales "Location" values start with `(GMT±…)` (or similar in parentheses).
 * Carbon Dropdown / Downshift keyboard typeahead uses `itemToString`; without
 * stripping this prefix, the first typed character is `(` and matching fails.
 *
 * Returns the text after the first `(...)` block, optionally with `ianaId`
 * appended so users can also type e.g. `America` to find `America/New_York`.
 */
export function getTimezoneTypeaheadString(fullLabel: string, ianaId?: string): string {
  const trimmed = fullLabel.trim();
  let rest = trimmed;
  if (/^\([^)]+\)/.test(trimmed)) {
    rest = trimmed.replace(/^\([^)]+\)\s*/, '').trim();
  }
  if (ianaId) {
    return `${rest} ${ianaId}`.trim();
  }
  return rest;
}

